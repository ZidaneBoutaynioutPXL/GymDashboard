import assert from 'node:assert/strict'
import {chromium} from 'playwright'
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true})
const context=await browser.newContext({viewport:{width:1440,height:1000}}),page=await context.newPage(),errors=[]
page.on('pageerror',e=>errors.push(e.message))
try{
  await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'})
  await page.locator('.onboarding').waitFor()
  assert.equal(await page.locator('.app-shell').count(),0)
  await page.screenshot({path:'tmp/onboarding-welcome.png',fullPage:true})
  await page.getByRole('button',{name:'BEGIN YOUR JOURNEY'}).click()
  assert.equal(await page.getByRole('button',{name:'SET YOUR MISSION'}).isDisabled(),true)
  await page.getByLabel('Athlete name').fill('Nova')
  await page.getByLabel('Age',{exact:true}).fill('29')
  await page.getByLabel('Bodyweight (kg)',{exact:true}).fill('80')
  await page.getByLabel('Comparison category').selectOption('M')
  await page.getByRole('button',{name:'SET YOUR MISSION'}).click()
  await page.getByRole('button',{name:'Back',exact:true}).click()
  assert.equal(await page.getByLabel('Athlete name').inputValue(),'Nova')
  await page.getByRole('button',{name:'SET YOUR MISSION'}).click()
  await page.getByRole('button',{name:'ENTER YOUR TRAINING UNIVERSE'}).click()
  await page.getByRole('heading',{name:/Welcome back, Nova/}).waitFor()
  await page.reload({waitUntil:'networkidle'})
  assert.equal(await page.locator('.onboarding').count(),0)
  await page.getByRole('button',{name:'My lifts',exact:true}).click()
  await page.locator('.warrior-card').first().waitFor()
  assert.equal(await page.locator('.warrior-card').count(),6)
  assert.equal(await page.locator('.detail-panel,.street-panel').count(),0,'No lift detail before opening a card')
  await page.screenshot({path:'tmp/lift-deck-desktop.png',fullPage:true})
  await page.getByRole('button',{name:'Open Weighted dip',exact:true}).click()
  await page.locator('.card-opening').waitFor()
  assert.equal(await page.locator('.opened-lift').count(),0)
  await page.locator('.opened-lift').waitFor()
  await page.getByRole('heading',{name:'Streetlifting standards'}).waitFor()
  await page.getByRole('button',{name:'LOG SET',exact:true}).click()
  await page.getByLabel('Added weight (kg)',{exact:true}).fill('20')
  await page.getByLabel('Reps',{exact:true}).fill('1')
  await page.getByRole('button',{name:'Save lift'}).click()
  await page.locator('.modal-card').waitFor({state:'hidden'})
  assert.equal(await page.locator('.history-row').count(),1)
  await page.getByRole('button',{name:'Delete set',exact:true}).click()
  await page.locator('.history-row').waitFor({state:'hidden'})
  await page.getByRole('button',{name:'UNDO DELETE'}).click()
  await page.locator('.history-row').waitFor()
  assert.equal(await page.locator('.history-row').count(),1)
  await page.getByRole('button',{name:'Remove from collection'}).click()
  assert.equal(await page.locator('.warrior-card').count(),5)
  await page.reload({waitUntil:'networkidle'})
  await page.getByRole('button',{name:'My lifts',exact:true}).click()
  await page.locator('.warrior-card').first().waitFor()
  assert.equal(await page.locator('.warrior-card').count(),5)
  await page.getByRole('button',{name:'Restore Weighted dip'}).click()
  await page.getByRole('button',{name:'Open Weighted dip',exact:true}).click()
  await page.locator('.opened-lift').waitFor()
  assert.equal(await page.locator('.history-row').count(),1,'Removing the card preserves logs')
  await page.getByRole('button',{name:'BACK TO YOUR CARDS'}).click()
  await page.setViewportSize({width:390,height:844})
  await page.waitForTimeout(1200)
  await page.screenshot({path:'tmp/lift-deck-mobile.png',fullPage:true})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.getByRole('button',{name:'Open Bench press',exact:true}).click()
  await page.locator('.opened-lift').waitFor()
  assert.equal(await page.locator('.card-opening').count(),0)
  await page.getByRole('button',{name:'BACK TO YOUR CARDS'}).click()
  await page.emulateMedia({reducedMotion:'no-preference'})
  await page.getByRole('button',{name:'Open Back squat',exact:true}).click()
  // Escape cancels the full-screen entrance and its pending transition.
  await page.keyboard.press('Escape')
  await page.locator('.lift-entrance').waitFor({state:'hidden'})
  await page.getByRole('button',{name:'Toggle menu'}).click()
  await page.getByRole('button',{name:'Notebook',exact:true}).click()
  await page.waitForTimeout(1900)
  assert.equal(await page.locator('.opened-lift').count(),0)
  assert.deepEqual(errors,[])
  const fresh=await browser.newContext({viewport:{width:390,height:844}}),mobile=await fresh.newPage()
  await mobile.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'})
  await mobile.locator('.onboarding').waitFor()
  await mobile.screenshot({path:'tmp/onboarding-mobile.png',fullPage:true})
  assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)
  await fresh.close()
  console.log('Experience tests passed: first-run onboarding, validation/back navigation, profile persistence, card-only collection, opening transition, detail/comparison/logging, delete/undo, remove/restore persistence, reduced motion, cancellation, mobile.')
}finally{await browser.close()}
