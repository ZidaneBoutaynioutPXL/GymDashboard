import { onboard } from './onboard.mjs'
import assert from 'node:assert/strict'
import {chromium} from 'playwright'
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true})
const context=await browser.newContext({viewport:{width:1280,height:900}}),page=await context.newPage(),errors=[]
page.on('pageerror',e=>errors.push(e.message))
try{
  await page.goto(process.env.BASE_URL||'http://127.0.0.1:5173/',{waitUntil:'networkidle'})
  await onboard(page)
  const math=await page.evaluate(async()=>{
    const {streetThresholds,streetComparison,streetReference}=await import('/src/street.ts')
    const {liftStats,displayWeight}=await import('/src/strength.ts')
    const {defaultProfile}=await import('/src/data.ts')
    const p={...defaultProfile,age:25,bodyweight:80,sex:'M'}
    const entry={id:'test',liftId:'pullup',weight:47.5,reps:1,bodyweight:80,date:'2026-09-23',note:''}
    return {dip:streetThresholds('dip','M',80),pull:streetThresholds('pullup','M',80),women:streetThresholds('dip','F',80),base:liftStats([{...entry,weight:20}], 'pullup',80,'M').rank,unlock:liftStats([entry],'pullup',80,'M').rank,top:liftStats([{...entry,weight:98.75}],'pullup',80,'M').rank,ref:streetReference('dip','M',80),fallback:streetReference('dip','F',100),median:streetComparison('dip',p,1.2004*80),unsupported:streetComparison('dip',{...p,sex:'Mx'},100),quarter:displayWeight(68.75,true)}
  })
  assert.deepEqual(math.dip,[68.75,85,101.25,117.5,132.5,146.25])
  assert.deepEqual(math.pull,[47.5,56.25,65,75,86.25,98.75])
  assert.ok(math.women[5]<math.dip[5]);assert.equal(math.base,0);assert.equal(math.unlock,1);assert.equal(math.top,6)
  assert.equal(math.ref.curve.n,170);assert.equal(math.ref.pooled,false);assert.equal(math.fallback.pooled,true)
  assert.equal(math.median.percentile,50);assert.equal(math.unsupported,null);assert.equal(math.quarter,'+68.75 kg')
  await page.locator('.evolution-card').last().click()
  await page.waitForFunction(()=>document.querySelector('video')?.currentTime>.5)
  assert.equal(await page.locator('video').count(),1)
  await page.getByRole('button',{name:'Mute rank sounds'}).click()
  assert.equal(await page.locator('video').evaluate(v=>v.muted),true)
  await page.getByRole('button',{name:'Enable rank sounds'}).click()
  assert.equal(await page.locator('video').evaluate(v=>v.muted),false)
  await page.getByLabel('Rank sound volume').fill('0.65')
  assert.equal(await page.locator('video').evaluate(v=>v.volume),.65)
  assert.ok(await page.locator('video').evaluate(v=>v.webkitAudioDecodedByteCount>0))
  await page.screenshot({path:'tmp/cinematic-desktop.png'})
  await page.getByRole('button',{name:'SKIP ANIMATION'}).click()
  await page.getByRole('heading',{name:'ULTRA INSTINCT',exact:true}).waitFor()
  await page.getByRole('button',{name:'Replay reveal'}).click()
  await page.waitForFunction(()=>document.querySelector('.final-form-reveal')?.dataset.phase==='finished')
  await page.getByRole('button',{name:'KEEP ASCENDING'}).click()
  await page.locator('.rank-reveal').waitFor({state:'hidden'})
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.locator('.evolution-card').last().click()
  assert.equal(await page.locator('.scene-running').count(),0)
  await page.getByRole('button',{name:'Replay reveal'}).click()
  await page.waitForFunction(()=>document.querySelector('video')?.currentTime>.2)
  await page.setViewportSize({width:390,height:844})
  await page.waitForTimeout(400)
  const bounds=await page.locator('.modal-card').boundingBox()
  assert.ok(bounds.x>=0&&bounds.x+bounds.width<=390)
  await page.screenshot({path:'tmp/cinematic-mobile.png'})
  await page.getByRole('button',{name:'Close',exact:true}).click()
  await page.locator('video').waitFor({state:'detached'})
  // A missing clip offers recovery and can always be skipped.
  await page.emulateMedia({reducedMotion:'no-preference'})
  await page.route('**/cinematics/finals/goku.mp4',route=>route.abort())
  await page.locator('.evolution-card').last().click()
  await page.getByRole('button',{name:'RETRY ANIMATION',exact:true}).waitFor()
  await page.getByRole('button',{name:'SKIP ANIMATION'}).click()
  await page.getByRole('button',{name:'KEEP ASCENDING'}).click()
  await page.unroute('**/cinematics/finals/goku.mp4')
  // Browser autoplay denial has a user-initiated play path.
  await page.evaluate(()=>{window.originalMediaPlay=HTMLMediaElement.prototype.play;HTMLMediaElement.prototype.play=function(){return Promise.reject(new DOMException('User gesture required','NotAllowedError'))}})
  await page.locator('.evolution-card').last().click()
  await page.getByRole('button',{name:'PLAY ANIMATION',exact:true}).waitFor()
  await page.evaluate(()=>{HTMLMediaElement.prototype.play=window.originalMediaPlay})
  await page.getByRole('button',{name:'PLAY ANIMATION',exact:true}).click()
  await page.waitForFunction(()=>document.querySelector('video')?.currentTime>.2)
  await page.getByRole('button',{name:'SKIP ANIMATION'}).click()
  await page.getByRole('button',{name:'KEEP ASCENDING'}).click()
  assert.deepEqual(errors,[])
  console.log('Cinematic and streetlifting tests passed: reference anchors, cohort/fallback counts, rank boundaries, quarter kg, decoded character playback, auto/opt-in play, mute, skip, replay, end state, close, mobile.')
}finally{await browser.close()}
